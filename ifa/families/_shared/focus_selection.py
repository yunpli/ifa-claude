"""Deterministic, market-driven focus selection for Market and Tech reports.

The focus sections are a system-generated market attention list, not a user
watchlist.  Selection is sector-first and stock-second:

1. take the report's PIT active SW L2 sectors;
2. rank their members with observable price, liquidity, order-flow and formal
   leader-role evidence;
3. split the ranked result into an action-oriented important tier and a lower
   conviction tracking tier.

LLMs never choose, add or reorder tickers.  The report run persists the audit
payload alongside the selected rows, so a historical report remains
explainable even when the next run produces a different list.

Slot semantics are deliberately asymmetric:

* morning: previous closed trading-day features;
* noon: strictly prior-day features plus today's realtime quote overlay;
* evening: today's closed features, with realtime overlay only when the local
  EOD pipeline has not finished yet.

There is no hard-coded ticker fallback.  If a source is unavailable we either
select from the remaining dynamic sources or return a visibly degraded/empty
selection.
"""
from __future__ import annotations

import datetime as dt
import math
from dataclasses import dataclass, field
from typing import Any, Iterable, Mapping, Sequence

import pandas as pd
from sqlalchemy import text
from sqlalchemy.engine import Engine

from ifa.core.report.timezones import BJT
from ifa.core.tushare import TuShareClient


LOGIC_VERSION = "dynamic_focus_v1_0"


@dataclass(frozen=True)
class FocusStock:
    """Stable report-facing focus-stock contract.

    ``note`` carries the deterministic selection explanation.  It is evidence
    for the narrative layer; it is never generated by the LLM.
    """

    ts_code: str
    display_name: str
    layer: str
    sub_theme: str
    note: str = ""


@dataclass
class FocusSelection:
    important: list[FocusStock]
    regular: list[FocusStock]
    audit: dict[str, Any]


@dataclass
class _Candidate:
    ts_code: str
    name: str = ""
    sector_code: str = ""
    sector_name: str = ""
    layer: str = "market"
    role: str = ""
    formal_score: float | None = None
    pct_change: float | None = None
    amount_yuan: float | None = None
    turnover_rate: float | None = None
    volume_ratio: float | None = None
    main_net_yuan: float | None = None
    main_net_ratio: float | None = None
    sector_state: str = ""
    sector_state_score: float | None = None
    sector_confidence: float | None = None
    sector_main_net_ratio: float | None = None
    diffusion_score: float | None = None
    quality_flag: str = ""
    risk_flags: list[str] = field(default_factory=list)
    source_tags: set[str] = field(default_factory=set)
    score: float = 0.0
    confirmations: int = 0
    selection_state: str = "tracking"
    reason: str = ""


