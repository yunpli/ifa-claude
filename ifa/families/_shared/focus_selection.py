def _percentile_map(
    candidates: Iterable[_Candidate], *, key
) -> dict[str, float]:
    valid: list[tuple[str, float]] = []
    for candidate in candidates:
        value = _f(key(candidate))
        if value is not None:
            valid.append((candidate.ts_code, value))
    if not valid:
        return {}
    valid.sort(key=lambda x: x[1])
    if len(valid) == 1:
        return {valid[0][0]: 1.0}
    return {code: idx / (len(valid) - 1) for idx, (code, _) in enumerate(valid)}


def _momentum_signal(pct: float | None) -> float:
    if pct is None:
        return 0.40
    points = [(-10.0, 0.05), (-3.0, 0.22), (0.0, 0.42), (3.0, 0.78), (7.0, 1.0), (12.0, 0.90), (25.0, 0.75)]
    if pct <= points[0][0]:
        return points[0][1]
    if pct >= points[-1][0]:
        return points[-1][1]
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if x0 <= pct <= x1:
            ratio = (pct - x0) / (x1 - x0)
            return y0 + (y1 - y0) * ratio
    return 0.40


def _normalise_ratio(value: float | None) -> float:
    if value is None:
        return 0.45
    return _clamp((value + 0.10) / 0.20, 0.0, 1.0, default=0.45)


def _normalise_turnover(value: float | None) -> float:
    if value is None:
        return 0.40
    return _clamp(value / 12.0, 0.0, 1.0, default=0.40)


def _normalise_volume_ratio(value: float | None) -> float:
    if value is None:
        return 0.40
    return _clamp((value - 0.5) / 2.0, 0.0, 1.0, default=0.40)


def _clamp(value: float | None, lo: float, hi: float, *, default: float) -> float:
    if value is None or not math.isfinite(value):
        return default
    return max(lo, min(hi, value))


def _f(value: Any) -> float | None:
    try:
        if value is None or pd.isna(value):
            return None
        return float(value)
    except (TypeError, ValueError):
        return None


def _first(first: float | None, second: float | None) -> float | None:
    return first if first is not None else second
